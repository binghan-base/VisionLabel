"""
全局配置与常量
==============

把“会变”的东西集中放在一个文件里，是工程上的好习惯：
以后想改窗口大小、增删标注模式、换默认颜色，只需要改这一个文件，
不用到处翻代码。

注意：本项目【没有内置标注类别】。类别标签完全来自用户 ——
要么从已有的标注文件（.json）里读出来，要么用户在标注时现场创建。
这里只有一组“颜色盘”：新标签被创建时，按顺序从颜色盘里取一个颜色。
"""

# ---------------------------------------------------------------------------
# 应用基本信息
# ---------------------------------------------------------------------------
APP_NAME = "VisionLabel" #软件名称
WINDOW_WIDTH = 1400   # 主窗口初始宽度（像素）
WINDOW_HEIGHT = 860   # 主窗口初始高度（像素）

# ---------------------------------------------------------------------------
# 左侧模式条的“标注模式”定义（数据驱动）
# ---------------------------------------------------------------------------
# 界面不是把按钮写死的，而是遍历下面这个列表自动生成。
# 这就是“可插拔架构”在界面层的体现：
# 以后新增一种标注类型（比如“旋转框”），只需在这里加一项，
# 再到 tools/ 目录里实现对应的工具类，按钮就会自动出现在模式条上。
#
# 每个模式是一个字典，字段含义：
#   key      内部标识（程序里用，要求唯一、英文）
#   name     界面上显示的名字
#   shortcut 切换到这个模式的快捷键
#   icon     图标种类（对应 resources/icons/ 里的 svg 文件名）
#   enabled  False 表示“预留占位”，按钮会显示为灰色不可点
MODES = [
    {"key": "select",  "name": "选择/编辑", "shortcut": "V", "icon": "cursor",  "enabled": True},
    {"key": "rect",    "name": "矩形框",    "shortcut": "R", "icon": "rect",    "enabled": True},
    {"key": "polygon", "name": "多边形",    "shortcut": "P", "icon": "polygon", "enabled": True},
    {"key": "point",   "name": "关键点",    "shortcut": "K", "icon": "point",   "enabled": False},
    # ---- 以下为预留的扩展位（功能未实现，按钮置灰）----
    {"key": "brush",   "name": "画笔",      "shortcut": "",  "icon": "brush",   "enabled": False},
    {"key": "line",    "name": "线段",      "shortcut": "",  "icon": "line",    "enabled": False},
]

# ---------------------------------------------------------------------------
# 类别颜色盘
# ---------------------------------------------------------------------------
# 新标签按创建顺序依次取色（用完一圈就循环）。
# 挑选原则：彼此之间区分度高、在深色画布上都醒目。
COLOR_PALETTE = [
    "#ff4d4f",  # 红
    "#52c41a",  # 绿
    "#fa8c16",  # 橙
    "#9254de",  # 紫
    "#13c2c2",  # 青
    "#eb2f96",  # 品红
    "#fadb14",  # 黄
    "#2f54eb",  # 蓝
    "#a0d911",  # 黄绿
    "#fa541c",  # 橘红
    "#722ed1",  # 深紫
    "#1890ff",  # 亮蓝
]

# 查不到颜色时的兜底色（比如标注文件里出现了颜色盘之外的情况）
FALLBACK_COLOR = "#999999"


def palette_color(index: int) -> str:
    """按序号从颜色盘取色；序号超过颜色数量时循环使用。"""
    return COLOR_PALETTE[index % len(COLOR_PALETTE)]
